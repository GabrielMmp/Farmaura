
CREATE DATABASE IF NOT EXISTS FARMALI
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE FARMALI;

CREATE TABLE IF NOT EXISTS LOGRADOURO (
    COD_LOGRADOURO INT AUTO_INCREMENT PRIMARY KEY,
    TIPO_LOGRADOURO VARCHAR(50) NOT NULL,
    NOME VARCHAR(250) NOT NULL,
    NUMERO VARCHAR(10),
    COMPLEMENTO VARCHAR(100),
    CIDADE VARCHAR(100) NOT NULL,
    ESTADO VARCHAR(100) NOT NULL,
    CEP VARCHAR(10) NOT NULL,
    PONTO_REFERENCIA VARCHAR(255),
    DATA_INCLUSAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STATUS ENUM('ATIVO','INATIVO') DEFAULT 'ATIVO'
);

CREATE TABLE IF NOT EXISTS CLIENTE (
    COD_CLIENTE INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(250) NOT NULL,
    DATA_NASCIMENTO DATE,
    EMAIL VARCHAR(255) UNIQUE,
    TELEFONE VARCHAR(20),
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    COD_LOGRADOURO_FK INT,
    FOREIGN KEY (COD_LOGRADOURO_FK)
        REFERENCES LOGRADOURO(COD_LOGRADOURO)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS FORNECEDOR (
    COD_FORNECEDOR INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(200) NOT NULL,
    CNPJ VARCHAR(20) UNIQUE,
    EMAIL VARCHAR(150),
    TELEFONE VARCHAR(20),
    CONTATO VARCHAR(100),
    STATUS ENUM('ATIVO','INATIVO') DEFAULT 'ATIVO',
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS CATEGORIA (
    COD_CATEGORIA INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    DESCRICAO TEXT,
    STATUS ENUM('ATIVO','INATIVO') DEFAULT 'ATIVO',
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS PRODUTO (
    COD_PRODUTO INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(250) NOT NULL,
    DESCRICAO TEXT,
    PRECO DECIMAL(10,2) NOT NULL,
    QUANTIDADE_ESTOQUE INT NOT NULL DEFAULT 0,
    DATA_VALIDADE DATE,
    IMAGEM_URL VARCHAR(500),
    COD_CATEGORIA_FK INT,
    DATA_INCLUSAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STATUS ENUM('ATIVO','INATIVO') DEFAULT 'ATIVO',
    FOREIGN KEY (COD_CATEGORIA_FK)
        REFERENCES CATEGORIA(COD_CATEGORIA)
);

CREATE TABLE IF NOT EXISTS PEDIDO_COMPRA (
    COD_PEDIDO INT AUTO_INCREMENT PRIMARY KEY,
    DATA_PEDIDO DATE NOT NULL,
    STATUS ENUM(
        'ABERTO',
        'FINALIZADO',
        'CANCELADO'
    ) DEFAULT 'ABERTO',
    COD_FORNECEDOR_FK INT,
    FOREIGN KEY (COD_FORNECEDOR_FK)
        REFERENCES FORNECEDOR(COD_FORNECEDOR)
);

CREATE TABLE IF NOT EXISTS ITEM_PEDIDO_COMPRA (
    COD_PEDIDO_FK INT NOT NULL,
    COD_PRODUTO_FK INT NOT NULL,
    QTD INT NOT NULL,
    PRECO_COMPRA DECIMAL(10,2),
    PRIMARY KEY (COD_PEDIDO_FK, COD_PRODUTO_FK),
    FOREIGN KEY (COD_PEDIDO_FK)
        REFERENCES PEDIDO_COMPRA(COD_PEDIDO),
    FOREIGN KEY (COD_PRODUTO_FK)
        REFERENCES PRODUTO(COD_PRODUTO)
);

CREATE TABLE IF NOT EXISTS NOTA_FISCAL (
    NUMERO_NF INT AUTO_INCREMENT PRIMARY KEY,
    DATA_EMISSAO DATE NOT NULL,
    DATA_VENCIMENTO DATE,
    VALOR_TOTAL DECIMAL(15,2) NOT NULL,
    STATUS ENUM(
        'PAGO',
        'PENDENTE',
        'CANCELADO'
    ) DEFAULT 'PENDENTE',
    FORMA_PAGAMENTO VARCHAR(50),
    OBSERVACOES TEXT,
    COD_CLIENTE_FK INT,
    DATA_INCLUSAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (COD_CLIENTE_FK)
        REFERENCES CLIENTE(COD_CLIENTE)
);

CREATE TABLE IF NOT EXISTS ITEM_NOTA_FISCAL (
    ID_ITEM INT AUTO_INCREMENT PRIMARY KEY,
    QTD_VENDIDA INT NOT NULL,
    PRECO_UNITARIO DECIMAL(15,2) NOT NULL,
    SUBTOTAL DECIMAL(15,2)
        GENERATED ALWAYS AS (
            QTD_VENDIDA * PRECO_UNITARIO
        ) STORED,
    NUMERO_NF_FK INT NOT NULL,
    COD_PRODUTO_FK INT NOT NULL,
    FOREIGN KEY (NUMERO_NF_FK)
        REFERENCES NOTA_FISCAL(NUMERO_NF),
    FOREIGN KEY (COD_PRODUTO_FK)
        REFERENCES PRODUTO(COD_PRODUTO)
);

